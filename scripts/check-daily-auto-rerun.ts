// Asserts Daily Auto's "Rerun": the replacement is created FIRST and the old article is
// removed only afterwards, so a failure never costs the existing article.
// Needs the dev server (the old article is deleted through the real DELETE route).
// Uses THROWAWAY docs (ZZRerun) on a fake day (2030-01-01), a fake generator, and removes
// everything again - no real article, slot or layout is touched, nothing is published.
//   npx tsx scripts/check-daily-auto-rerun.ts
import fs from 'fs';
import mongoose from 'mongoose';

const env = fs.readFileSync('.env.local', 'utf8').replace(/^\uFEFF/, '');
for (const l of env.split(/\r?\n/)) { const m = l.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)$/); if (m && !process.env[m[1]]) process.env[m[1]] = m[2].trim().replace(/^["']|["']$/g, ''); }

let failed = 0;
const eq = (n: string, got: unknown, want: unknown) => { const ok = JSON.stringify(got) === JSON.stringify(want); if (!ok) failed++; console.log(`${ok ? 'ok  ' : 'FAIL'} ${n}${ok ? '' : `\n       got  ${JSON.stringify(got)}\n       want ${JSON.stringify(want)}`}`); };

(async () => {
  const dbConnect = (await import('../src/lib/mongoose')).default;
  await dbConnect();
  const { Person } = await import('../src/models/Almanac');
  const Article = (await import('../src/models/Article')).default;
  const Poll = (await import('../src/models/Poll')).default;
  const PollVote = (await import('../src/models/PollVote')).default;
  const { DailyAutoRun } = await import('../src/models/DailyAuto');
  const { rerunSlot } = await import('../src/lib/dailyAuto');

  // Berlin 06:00 on a fake day: before the 13:00 slot starts, so a replacement stays "ready"
  const NOW = new Date('2030-01-01T05:00:00Z'), DAY = '2030-01-01', SLOT = '1300', ORIGIN = 'http://localhost:3000';
  const mkArticle = (t: string, extra: any = {}) => Article.create({ title: `ZZRerun ${t}`, content: '<p>x</p>', status: 'draft', autoGenerated: true, ...extra });
  const exists = async (M: any, id: any) => !!(id && await M.exists({ _id: id }));
  const run = async () => DailyAutoRun.findOne({ dayKey: DAY, slotId: SLOT }).lean<any>();

  /** previous output of the slot: person + article + rankroll + a vote, and the run record */
  async function seed(phase: 'ready' | 'published', autoGenerated = true) {
    await DailyAutoRun.deleteMany({ dayKey: DAY });
    const person: any = await Person.create({ firstname: 'ZZRerun', lastname: `P${Math.random().toString(36).slice(2, 7)}`, profession: 'Other', hasArticle: true });
    const poll: any = await Poll.create({ title: 'ZZRerun poll', type: 'ranking', items: [{ id: 'a', title: 'a' }, { id: 'b', title: 'b' }], status: 'draft', category: 'ranking', personRef: person._id });
    await PollVote.create({ pollId: poll._id, optionId: 'a', oderId: 'zz-test', voteType: 'up' });
    const art: any = await mkArticle('old', { autoGenerated, personRef: person._id });
    await Person.updateOne({ _id: person._id }, { $set: { articleId: art._id } });
    await DailyAutoRun.create({ dayKey: DAY, slotId: SLOT, phase, articleId: String(art._id), pollId: String(poll._id), personName: 'ZZRerun Old', message: 'old' });
    return { person, poll, art };
  }

  try {
    // A: draft waiting for its start -> replaced, stays a draft waiting for its start
    let old = await seed('ready');
    let seenExclude: string[] = [];
    let fresh: any;
    let msg = await rerunSlot(SLOT, ORIGIN, {
      now: NOW,
      generate: async (_s, _o, _d, replace) => {
        seenExclude = Array.from(replace?.excludePersonIds ?? []);
        fresh = await mkArticle('new');
        return { articleId: String(fresh._id), personName: 'ZZRerun New', message: 'new' };
      },
    });
    eq('A: the generator is told to skip the replaced person', seenExclude, [String(old.person._id)]);
    eq('A: old article is deleted', await exists(Article, old.art._id), false);
    eq('A: old rankroll is deleted', await exists(Poll, old.poll._id), false);
    eq('A: its votes are deleted', await PollVote.countDocuments({ pollId: old.poll._id }), 0);
    const freed: any = await Person.findById(old.person._id).lean();
    eq('A: the person is released (hasArticle false, articleId cleared)', [freed.hasArticle, freed.articleId ?? null], [false, null]);
    eq('A: new article exists', await exists(Article, fresh._id), true);
    let r = await run();
    eq('A: record points at the new article and is "ready" (waits for 13:00)', [r.articleId, r.phase, r.personName], [String(fresh._id), 'ready', 'ZZRerun New']);
    eq('A: nothing was published', (await Article.findById(fresh._id).lean<any>()).status, 'draft');
    eq('A: reports it', msg.startsWith('replaced, goes live'), true);

    // B: the generator fails -> NOTHING is lost, record restored
    old = await seed('published');
    let threw = '';
    try { await rerunSlot(SLOT, ORIGIN, { now: NOW, generate: async () => { throw new Error('boom'); } }); } catch (e: any) { threw = e.message; }
    eq('B: the error reaches the caller', threw, 'boom');
    eq('B: old article still there', await exists(Article, old.art._id), true);
    eq('B: old rankroll still there', await exists(Poll, old.poll._id), true);
    eq('B: person untouched', (await Person.findById(old.person._id).lean<any>()).hasArticle, true);
    r = await run();
    eq('B: record restored (published, old ids)', [r.phase, r.articleId, r.pollId], ['published', String(old.art._id), String(old.poll._id)]);

    // C: the generator hands back the CURRENT article again -> must not delete it
    old = await seed('ready');
    threw = '';
    try { await rerunSlot(SLOT, ORIGIN, { now: NOW, generate: async () => ({ articleId: String(old.art._id) }) }); } catch (e: any) { threw = e.message; }
    eq('C: aborts', threw.includes('returned the current article again'), true);
    eq('C: the current article survives', await exists(Article, old.art._id), true);

    // D: nothing new generated (e.g. Winners "no games played") -> keep the old one
    old = await seed('ready');
    threw = '';
    try { await rerunSlot(SLOT, ORIGIN, { now: NOW, generate: async () => ({ live: true, message: 'Nothing to report' }) }); } catch (e: any) { threw = e.message; }
    eq('D: aborts with the reason', threw, 'Nothing to report');
    eq('D: old article survives', await exists(Article, old.art._id), true);

    // E: an article an editor wrote is never deleted, and nothing is generated
    old = await seed('ready', false);
    let called = false;
    threw = '';
    try { await rerunSlot(SLOT, ORIGIN, { now: NOW, generate: async () => { called = true; return { articleId: 'x' }; } }); } catch (e: any) { threw = e.message; }
    eq('E: refuses', threw.includes('not generated automatically'), true);
    eq('E: generator not called', called, false);
    eq('E: the editor article survives', await exists(Article, old.art._id), true);

    // F: the old one was LIVE and the replacement is live straight away (Winners-style) -> "published"
    old = await seed('published');
    fresh = null;
    msg = await rerunSlot(SLOT, ORIGIN, {
      now: NOW,
      generate: async () => { fresh = await mkArticle('new live', { tags: ['daily-winners'] }); return { articleId: String(fresh._id), live: true, message: 'winners' }; },
    });
    r = await run();
    eq('F: record is "published" with the new article', [r.phase, r.articleId], ['published', String(fresh._id)]);
    eq('F: old article deleted', await exists(Article, old.art._id), false);

    // G: an unknown slot is rejected
    await DailyAutoRun.deleteMany({ dayKey: DAY });
    threw = '';
    try { await rerunSlot('nope', ORIGIN, { now: NOW }); } catch (e: any) { threw = e.message; }
    eq('G: unknown slot is rejected', threw, 'Unknown slot nope');
  } finally {
    await DailyAutoRun.deleteMany({ dayKey: DAY });
    await Article.deleteMany({ title: /^ZZRerun/ });
    await Poll.deleteMany({ title: /^ZZRerun/ });
    await PollVote.deleteMany({ oderId: 'zz-test' });
    await Person.deleteMany({ firstname: 'ZZRerun' });
    const left = (await Article.countDocuments({ title: /^ZZRerun/ })) + (await Poll.countDocuments({ title: /^ZZRerun/ })) + (await Person.countDocuments({ firstname: 'ZZRerun' })) + (await DailyAutoRun.countDocuments({ dayKey: DAY })) + (await PollVote.countDocuments({ oderId: 'zz-test' }));
    console.log('cleanup: leftovers =', left);
    await mongoose.disconnect();
  }
  console.log(failed ? `\n${failed} FAILED` : '\nall ok');
  process.exit(failed ? 1 : 0);
})();
