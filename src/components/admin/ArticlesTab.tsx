  _id?: string;
  title: string;
  subtitle?: string;
  content: string;
  coverImage?: string;
  imageScale?: number;
  imagePosition?: 'top' | 'center' | 'bottom' | 'left' | 'right';
  imagePosX?: number;
  imagePosY?: number;
  contentType?: 'article' | 'rankroll' | 'tv' | 'radio' | 'arcade' | 'shop';
  linkedContentId?: string;
  mainCategory: string;
  category: string;
  tags: string[];
  authorName?: string;
  status: 'draft' | 'published' | 'archived';
  layout: 'featured' | 'trending' | 'standard';
  order?: number;
  featured: boolean;
